/// The work counters of staged fact walks.
#[derive(Default)]
struct StagedWalkWork {
    fact_nodes: u64,
    canonical_evaluations: u64,
    scope_nodes: u64,
    scope_materializations: u64,
}

impl StagedWalkWork {
    fn accrue(&mut self, other: Self) {
        self.fact_nodes = self.fact_nodes.saturating_add(other.fact_nodes);
        self.canonical_evaluations = self
            .canonical_evaluations
            .saturating_add(other.canonical_evaluations);
        self.scope_nodes = self.scope_nodes.saturating_add(other.scope_nodes);
        self.scope_materializations = self
            .scope_materializations
            .saturating_add(other.scope_materializations);
    }
}

/// What one staged fact walk produced.
struct StagedFacts {
    selections: AHashMap<InstRef, crate::sema::ComptimeSelection>,
    call_facts: GenericCallFacts,
    frontier: VecDeque<ComptimeInferenceFrontier>,
    work: StagedWalkWork,
    /// The walk's staged types predate a typed call's facts where a selector
    /// depends on them; see `collect_staged_facts`.
    deferred: bool,
    /// The walk passed a typed call whose facts retype it beyond what its
    /// staged pass had, so a queued frontier's bindings may be stale.
    stale: bool,
}

/// What one staged fact walk collects.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum FactWalk {
    /// Generic-call facts and comptime selections, queueing each selected
    /// body as a frontier.
    Select,
    /// Generic-call facts only, over the code the staged pass just typed: no
    /// selector is evaluated, and no branch or match body is entered, since
    /// a staged pass stops at every selector of a value-specialized body.
    CallsOnly,
}

/// A body whose constraints become reachable after a canonical comptime
/// selector has been evaluated.  Staged inference consumes these frontiers
/// once, preserving the already-generated probe rather than replaying the
/// function prefix for every selector.
#[derive(Debug, Clone)]
struct ComptimeInferenceFrontier {
    body: InstRef,
    bindings: FrontierScope,
}

/// Exact lexical checkpoint state captured at a selector boundary.  A local
/// binding is identified by its Alloc instruction, rather than reconstructed
/// from a name-only map (which is ambiguous under shadowing and repeated
/// lexical names). Pattern bindings have no standalone Alloc node, so their
/// exact payload type is carried directly from the matched enum definition.
#[derive(Debug, Clone)]
struct FrontierBinding {
    name: Spur,
    ty: Option<Type>,
    /// A precomputed comptime type value carried by this binding. This is
    /// separate from `ty`, which is the runtime expression type used by the
    /// inference overlay (`COMPTIME_TYPE` for an alias binding).
    alias_ty: Option<Type>,
    mode: RirParamMode,
}

/// Persistent lexical checkpoint. Cloning a scope for each child only clones
/// the checkpoint pointer; typed and runtime-name lookups use their persistent
/// bounded tries instead of copying or flattening the visible prefix.
type FrontierScope = Option<Arc<FrontierScopeNode>>;

#[derive(Debug, Clone)]
#[allow(dead_code)]
struct FrontierScopeNode {
    binding: FrontierBinding,
    parent: FrontierScope,
    overlay: Option<Arc<FrontierParamOverlay>>,
    lexical_bindings: Arc<LexicalBindingTrieNode>,
}

#[derive(Debug, Clone)]
enum LexicalBinding {
    Runtime,
    ComptimeType(Type),
    /// A runtime local whose inferred type is a module (`let m = lib`): a
    /// runtime binding to every value lookup, and a module-path root
    /// (RUE-2426).
    Module(Type),
}

#[derive(Debug, Clone)]
struct LexicalBindingTrieNode {
    value: Option<LexicalBinding>,
    children: [Option<Arc<LexicalBindingTrieNode>>; 2],
}

impl LexicalBindingTrieNode {
    fn empty() -> Arc<Self> {
        Arc::new(Self {
            value: None,
            children: [None, None],
        })
    }

    fn insert(node: &Arc<Self>, key: u32, bit: u32, value: LexicalBinding) -> Arc<Self> {
        if bit == 32 {
            return Arc::new(Self {
                value: Some(value),
                children: node.children.clone(),
            });
        }
        let index = ((key >> (31 - bit)) & 1) as usize;
        let child = node.children[index].clone().unwrap_or_else(Self::empty);
        let updated = Self::insert(&child, key, bit + 1, value);
        let mut children = node.children.clone();
        children[index] = Some(updated);
        Arc::new(Self {
            value: node.value.clone(),
            children,
        })
    }

    fn lookup(node: &Arc<Self>, key: u32, bit: u32) -> Option<LexicalBinding> {
        if bit == 32 {
            return node.value.clone();
        }
        let index = ((key >> (31 - bit)) & 1) as usize;
        node.children[index]
            .as_ref()
            .and_then(|child| Self::lookup(child, key, bit + 1))
    }
}

impl<H: OrdinaryBodyAnalysisHost> OrdinaryBodyEngine<'_, H> {
    /// Flatten the payload bindings one match pattern introduces, in the order
    /// they enter scope, pairing each with the payload field type it takes.
    /// A nested variant pattern (RUE-2053) matches against the field's own
    /// type, so its bindings are resolved through that type's enum definition.
    fn flatten_pattern_bindings(
        &self,
        pattern: &rue_rir::RirPatternView<'_>,
        payload_types: Option<&[Type]>,
        out: &mut Vec<(lasso::Spur, Option<Type>)>,
    ) {
        let rue_rir::RirPatternView::Path { elements, .. } = pattern else {
            return;
        };
        for (index, element) in elements.iter().enumerate() {
            let field_ty = payload_types.and_then(|types| types.get(index).copied());
            match element {
                rue_rir::RirPatternElementView::Binding(name) => out.push((name, field_ty)),
                rue_rir::RirPatternElementView::Nested(nested) => {
                    let nested_payload = field_ty.and_then(|ty| ty.as_enum()).and_then(|enum_id| {
                        let def = self.body_type_pool().enum_def(enum_id);
                        let rue_rir::RirPatternView::Path { variant, .. } = &nested else {
                            return None;
                        };
                        let variant_name = self.body_interner().resolve(variant);
                        def.find_variant(variant_name)
                            .map(|position| def.variant_payload(position).to_vec())
                    });
                    self.flatten_pattern_bindings(&nested, nested_payload.as_deref(), out);
                }
            }
        }
    }

    fn push_frontier_scope(
        &self,
        scope: &FrontierScope,
        binding: FrontierBinding,
    ) -> FrontierScope {
        let binding_name = binding.name;
        let parent_overlay = scope.as_ref().and_then(|node| node.overlay.clone());
        let parent_lexical_bindings = scope
            .as_ref()
            .map(|node| node.lexical_bindings.clone())
            .unwrap_or_else(LexicalBindingTrieNode::empty);
        let lexical_binding = match (binding.alias_ty, binding.ty) {
            (Some(alias), _) => LexicalBinding::ComptimeType(alias),
            (None, Some(ty)) if ty.as_module().is_some() => LexicalBinding::Module(ty),
            (None, _) => LexicalBinding::Runtime,
        };
        let overlay = binding
            .ty
            .map(|ty| {
                FrontierParamOverlay::insert(
                    parent_overlay.as_ref(),
                    binding.name,
                    ParamVarInfo {
                        ty: self.type_to_infer_type(ty),
                        is_inout: binding.mode == RirParamMode::Inout,
                    },
                )
            })
            .or(parent_overlay);
        Some(Arc::new(FrontierScopeNode {
            binding,
            parent: scope.clone(),
            overlay,
            lexical_bindings: LexicalBindingTrieNode::insert(
                &parent_lexical_bindings,
                binding_name.into_usize() as u32,
                0,
                lexical_binding,
            ),
        }))
    }
}

fn lexical_binding_membership_view(
    scope: &FrontierScope,
) -> std::sync::Arc<dyn Fn(&Spur) -> Option<crate::sema::ComptimeLocalBinding<Type>>> {
    let scope = scope.clone();
    std::sync::Arc::new(move |name| {
        scope
            .as_ref()
            .and_then(|node| {
                LexicalBindingTrieNode::lookup(&node.lexical_bindings, name.into_usize() as u32, 0)
            })
            .map(|binding| match binding {
                LexicalBinding::Runtime | LexicalBinding::Module(_) => {
                    crate::sema::ComptimeLocalBinding::Runtime
                }
                LexicalBinding::ComptimeType(ty) => crate::sema::ComptimeLocalBinding::Type(ty),
            })
    })
}

/// The module a `let`-bound module in lexical scope holds, for the comptime
/// engine's module-path roots (RUE-2426).
fn lexical_module_membership_view(
    scope: &FrontierScope,
) -> std::sync::Arc<dyn Fn(&Spur) -> Option<Type>> {
    let scope = scope.clone();
    std::sync::Arc::new(move |name| {
        scope
            .as_ref()
            .and_then(|node| {
                LexicalBindingTrieNode::lookup(&node.lexical_bindings, name.into_usize() as u32, 0)
            })
            .and_then(|binding| match binding {
                LexicalBinding::Module(ty) => Some(ty),
                LexicalBinding::Runtime | LexicalBinding::ComptimeType(_) => None,
            })
    })
}

fn lexical_binding_capture_view(
    scope: &FrontierScope,
) -> std::sync::Arc<dyn Fn() -> Vec<(Spur, crate::sema::ComptimeLocalBinding<Type>)>> {
    let scope = scope.clone();
    std::sync::Arc::new(move || {
        let mut result = Vec::new();
        let mut seen = ahash::AHashSet::new();
        let mut current = scope.clone();
        while let Some(node) = current {
            if seen.insert(node.binding.name) {
                result.push((
                    node.binding.name,
                    node.binding.alias_ty.map_or(
                        crate::sema::ComptimeLocalBinding::Runtime,
                        crate::sema::ComptimeLocalBinding::Type,
                    ),
                ));
            }
            current = node.parent.clone();
        }
        result
    })
}

/// What resolves a method-call receiver to a module for
/// [`OrdinaryBodyEngine::generic_callee_key`].
#[derive(Clone, Copy)]
enum ReceiverFacts<'a> {
    /// The fact collector's inferred types, which resolve any receiver.
    Resolved(&'a AHashMap<InstRef, Type>),
    /// The pre-pass gate, which runs before inference: the `let`-bound
    /// modules in lexical scope at the call.
    Syntactic(&'a LocalModuleScope),
}

/// The `let` bindings in lexical scope at one point of a body walk that runs
/// before inference, each with the module its initializer names, or `None`
/// for a local that is not a module (which still shadows a file-level
/// binding). The pre-pass gate and the comptime type-local precompute
/// (`precompute_comptime_type_locals`) both keep one.
#[derive(Default)]
pub(crate) struct LocalModuleScope {
    bindings: AHashMap<Spur, Vec<Option<crate::types::ModuleId>>>,
}

impl LocalModuleScope {
    pub(crate) fn bind(&mut self, name: Spur, module: Option<crate::types::ModuleId>) {
        self.bindings.entry(name).or_default().push(module);
    }

    pub(crate) fn unbind(&mut self, name: Spur) {
        if let Some(stack) = self.bindings.get_mut(&name) {
            stack.pop();
            if stack.is_empty() {
                self.bindings.remove(&name);
            }
        }
    }

    /// `Some` when a `let` named `name` is in scope: the module it names, if any.
    pub(crate) fn lookup(&self, name: Spur) -> Option<Option<crate::types::ModuleId>> {
        self.bindings
            .get(&name)
            .and_then(|stack| stack.last().copied())
    }
}

/// What the staged pre-pass learned about this body's generic calls, from
/// the canonical semantic evaluator, for the final inference pass to use.
#[derive(Default, Clone)]
struct GenericCallFacts {
    /// Each evaluated comptime argument, keyed by the argument's `InstRef`.
    argument_values: AHashMap<InstRef, ConstValue>,
    /// Each call's return type with its comptime arguments substituted, keyed
    /// by the call's `InstRef`, for a declared return type that constraint
    /// generation cannot reduce itself: a type-function application such as
    /// `-> Box(T)` (RUE-2425).
    return_types: AHashMap<InstRef, Type>,
    /// Each runtime argument's parameter type with the call's comptime
    /// arguments substituted, keyed by the argument's `InstRef`, for a
    /// declared parameter type constraint generation cannot reduce itself: a
    /// dependent type-function application such as `v: Sel(B)` (RUE-2436).
    param_types: AHashMap<InstRef, Type>,
}

impl GenericCallFacts {
    fn extend(&mut self, other: Self) {
        self.argument_values.extend(other.argument_values);
        self.return_types.extend(other.return_types);
        self.param_types.extend(other.param_types);
    }

    /// The facts that retype a call's result or runtime arguments. An
    /// argument value alone retypes nothing: a call whose signature depends
    /// on it has a substituted return or parameter type here as well.
    fn typing_facts(&self) -> usize {
        self.return_types.len() + self.param_types.len()
    }

    /// Whether this set retypes `call`'s result or one of its arguments where
    /// `staged`, the facts a staged pass was generated with, did not.
    fn retypes_beyond(
        &self,
        staged: &Self,
        call: InstRef,
        call_args: &[rue_rir::RirCallArg],
    ) -> bool {
        (self.return_types.contains_key(&call) && !staged.return_types.contains_key(&call))
            || call_args.iter().any(|arg| {
                self.param_types.contains_key(&arg.value)
                    && !staged.param_types.contains_key(&arg.value)
            })
    }

    /// Merge `other`, reporting whether it added a typing fact this set
    /// lacked.
    fn absorb(&mut self, other: Self) -> bool {
        let before = self.typing_facts();
        self.extend(other);
        self.typing_facts() != before
    }
}

